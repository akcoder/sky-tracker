#!/usr/bin/env python3
"""components/sky_tracker/sky_coast.h: the world's coastlines for the eclipse view's map (UI-87), from Natural Earth's
110m coastline (public domain, https://www.naturalearthdata.com), simplified to ~0.7 degrees. Each point is a lon, lat pair in
hundredths of a degree (int16); a line ends with the pair 32767, 32767.
  tools/gen_coast.py ne_110m_coastline.geojson"""
import json, math, os, sys

TOL = 0.35  # degrees


def rdp(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-9
    best, bi = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / n
        if d > best:
            best, bi = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return rdp(pts[:bi + 1], tol)[:-1] + rdp(pts[bi:], tol)


src = json.load(open(sys.argv[1]))
lines = []
for f in src["features"]:
    g = f["geometry"]
    for ln in (g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]):
        s = rdp([(p[0], p[1]) for p in ln], TOL)
        if len(s) >= 2:
            lines.append(s)
vals = []
for s in lines:
    for lon, lat in s:
        vals += [round(lon * 100), round(lat * 100)]
    vals += [32767, 32767]
out = ["#pragma once", "// Generated by tools/gen_coast.py: world coastlines (Natural Earth 110m, public domain), lon/lat in 1/100 degree,",
       "// a line ends with 32767, 32767.", "#include <cstdint>", "namespace sat {", "namespace coast {",
       f"constexpr int N = {len(vals) // 2};", "inline const int16_t PTS[] = {"]
out += [",".join(str(v) for v in vals[i:i + 24]) + "," for i in range(0, len(vals), 24)]
out += ["};", "}  // namespace coast", "}  // namespace sat", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "components", "sky_tracker", "sky_coast.h"), "w").write("\n".join(out))
print(len(lines), "lines,", len(vals) // 2, "points,", len(vals) * 2 // 1024, "KB")
