#!/usr/bin/env python3
"""components/sky_tracker/sky_photos_icons.h: the Planets strip's 40 px pictures of Mercury, Venus, Mars and Jupiter,
made from the built-in photos (sky_photos.h), as Uranus, Neptune, Pluto and Earth are (sky_photos_outer.h). ARGB8888, round.
  tools/gen_planet_icons.py"""
import io, os, re
from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "components", "sky_tracker")
NAMES = ["MERCURY", "VENUS", "MARS", "JUPITER"]  # (Saturn keeps its drawn icon: a cut from the photo looked bad)
src = open(os.path.join(ROOT, "sky_photos.h")).read()


def photo(name):
    m = re.search(rf"static const uint8_t {name}\[\] = \{{(.*?)\}};", src, re.S)
    return Image.open(io.BytesIO(bytes(int(x) for x in re.findall(r"\d+", m.group(1))))).convert("RGB")


def square(im, name):
    g = im.convert("L").point(lambda v: 255 if v > 40 else 0).getbbox()
    cx, cy = (g[0] + g[2]) / 2, (g[1] + g[3]) / 2
    r = max(g[2] - g[0], g[3] - g[1]) / 2
    h = r + 1
    return im.crop((round(cx - h), round(cy - h), round(cx + h), round(cy + h)))


out = ["#pragma once",
       "// Generated by tools/gen_planet_icons.py: the Planets strip's 40 px pictures of Mercury .. Jupiter (ARGB8888, round),",
       "// from the built-in photos. icon(p): p as planets:: (MERCURY 0, VENUS 1, MARS 2, JUPITER 3).",
       "#include <cstdint>", "namespace sat {", "namespace photos {"]
for n in NAMES:
    d = square(photo(n), n).resize((44, 44), Image.LANCZOS).crop((2, 2, 42, 42))
    a = Image.new("L", (160, 160), 0)
    ImageDraw.Draw(a).ellipse((0, 0, 159, 159), fill=255)
    d.putalpha(a.resize((40, 40), Image.LANCZOS))
    px = [(al << 24) | (r << 16) | (g << 8) | b for (r, g, b, al) in d.convert("RGBA").getdata()]
    out.append(f"static const uint32_t ICON_{n}[40 * 40] = {{")
    out += [",".join(f"0x{v:08X}" for v in px[i:i + 10]) + "," for i in range(0, len(px), 10)]
    out.append("};")
out.append("inline const uint32_t *icon(int p) {")
out.append("  static const uint32_t *const I[4] = {" + ", ".join("ICON_" + n for n in NAMES) + "};")
out.append("  return I[p < 0 ? 0 : p > 3 ? 3 : p];")
out.append("}")
out += ["}  // namespace photos", "}  // namespace sat", ""]
open(os.path.join(ROOT, "sky_photos_icons.h"), "w").write("\n".join(out))
print("wrote sky_photos_icons.h")
