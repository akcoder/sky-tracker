#!/usr/bin/env python3
"""components/sky_tracker/sky_moon_full.h: a picture of the full Moon for the eclipse view (UI-87): NASA SVS Dial-A-Moon
(public domain), the full Moon of 7 Sep 2025 18:00 UTC, cropped to the disc and made 164 x 164 (the view's Moon is 164 px across).
  tools/gen_moon_photo.py"""
import io, json, os, urllib.request
from PIL import Image

D = 164
api = json.load(urllib.request.urlopen("https://svs.gsfc.nasa.gov/api/dialamoon/2025-09-07T18:00"))
im = Image.open(io.BytesIO(urllib.request.urlopen(api["image"]["url"]).read())).convert("L")
box = im.point(lambda v: 255 if v > 18 else 0).getbbox()
cx, cy, r = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2, max(box[2] - box[0], box[3] - box[1]) / 2
im = im.crop((round(cx - r), round(cy - r), round(cx + r), round(cy + r))).resize((D, D), Image.LANCZOS).convert("RGB")
buf = io.BytesIO()
im.save(buf, "JPEG", quality=88, subsampling=0)
data = buf.getvalue()
out = ["#pragma once", "// Generated by tools/gen_moon_photo.py: the full Moon (NASA SVS Dial-A-Moon, 2025-09-07 18:00 UTC), 164 x 164 JPEG.",
       "#include <cstdint>", "namespace sat {", "namespace moonfull {", f"constexpr int DIM = {D};", f"constexpr unsigned LEN = {len(data)};",
       "inline const uint8_t DATA[] = {"]
out += [",".join(str(b) for b in data[i:i + 32]) + "," for i in range(0, len(data), 32)]
out += ["};", "}  // namespace moonfull", "}  // namespace sat", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "components", "sky_tracker", "sky_moon_full.h"), "w").write("\n".join(out))
print(len(data), "bytes")
