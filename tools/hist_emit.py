#!/usr/bin/env python3
"""tools/hist_pics.json -> components/sky_tracker/sky_hist_pics.h (UI-77b), and with `sheet` a contact sheet
tools/out/hist_sheet_N.png of the chosen pictures, numbered by event, to look at before they go in."""
import json, os, re, sys
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
res = json.load(open(os.path.join(HERE, "hist_pics.json")))
ev = re.findall(r'\{(\d+), (\d+), (\d+), "((?:[^"\\]|\\.)*)"\}', open(os.path.join(HERE, "..", "components/sky_tracker/sky_history.h")).read())
n = len(ev)
if sys.argv[1:] == ["sheet"]:
    per = 30
    for s0 in range(0, n, per):
        sheet = Image.new("RGB", (6 * 200, 5 * 160), (20, 20, 40))
        d = ImageDraw.Draw(sheet)
        for k in range(per):
            i = s0 + k
            if i >= n:
                break
            x, y = (k % 6) * 200, (k // 6) * 160
            f = os.path.join(HERE, "out", "hist", "%03d.jpg" % i)
            if res.get(str(i)) and os.path.exists(f):
                im = Image.open(f).convert("RGB")
                im.thumbnail((196, 140))
                sheet.paste(im, (x + 2, y + 2))
            d.text((x + 4, y + 144), "%d %s" % (i, ev[i][3][:30]), fill=(255, 255, 255))
        sheet.save(os.path.join(HERE, "out", "hist_sheet_%d.png" % (s0 // per)))
    sys.exit()
out = ["// generated by tools/hist_emit.py from tools/hist_pics.json (UI-77b): each event's Wikimedia Commons thumbnail,",
       "// the part after https://upload.wikimedia.org/wikipedia/commons/thumb/ (nullptr: no picture)", "static const char *const PIC[%d] = {" % n]
for i in range(n):
    r = res.get(str(i))
    if r:
        path = r["thumb"].split("/commons/thumb/", 1)[1]
        out.append('    "%s",  // %d %s: %s, %s' % (path, i, ev[i][3][:36].replace("\\", ""), r["title"][5:60], r["lic"]))
    else:
        out.append("    nullptr,  // %d %s" % (i, ev[i][3][:36].replace("\\", "")))
out.append("};")
open(os.path.join(HERE, "..", "components/sky_tracker/sky_hist_pics.h"), "w").write("\n".join(out) + "\n")
print(sum(1 for i in range(n) if res.get(str(i))), "of", n, "have a picture")
